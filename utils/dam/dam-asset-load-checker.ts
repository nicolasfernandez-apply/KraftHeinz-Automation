import { Page } from '@playwright/test';

export type AssetIssueType = 'invalid-url' | 'asset-not-loading';

export interface AssetIssue {
  /** alt / aria-label / title, falling back to the filename from the asset URL. */
  label: string;
  issueType: AssetIssueType;
  /** Absolute (or raw, if unresolvable) asset URL, for triage. */
  url: string;
  /** DOM origin of the reference, e.g. "img[src]", "video[poster]". */
  source: string;
}

export interface PageAssetLoadResult {
  assetsChecked: number;
  issues: AssetIssue[];
}

/**
 * How long to wait for an asset that has not yet resolved (no `complete`/
 * `readyState` signal) before treating it as not loading. Lazy-loaded assets
 * below the fold are scrolled into view by the caller before this runs, so a
 * short timeout is enough to catch genuinely broken sources.
 */
const LOAD_TIMEOUT_MS = 10_000;

/**
 * Walks the rendered page, resolves every image/video asset reference and
 * waits for each to either load or fail, inside the browser. Returns one
 * issue per asset reference that:
 *   - has an empty/malformed/unresolvable source ("invalid-url"), or
 *   - has a resolvable source that never renders — broken image icon, video
 *     that never reaches HAVE_METADATA, iframe that errors out ("asset-not-loading").
 */
export async function checkPageAssetLoading(page: Page): Promise<PageAssetLoadResult> {
  return page.evaluate(async (timeoutMs) => {
    type IssueType = 'invalid-url' | 'asset-not-loading';
    const issues: { label: string; issueType: IssueType; url: string; source: string }[] = [];
    let checked = 0;
    const seen = new Set<string>();

    function labelOf(el: Element, fallbackUrl: string): string {
      const explicit = (
        el.getAttribute('alt') ||
        el.getAttribute('aria-label') ||
        el.getAttribute('title') ||
        ''
      ).replace(/\s+/g, ' ').trim();
      if (explicit) return explicit;
      try {
        const file = new URL(fallbackUrl, document.baseURI).pathname.split('/').pop();
        return file || fallbackUrl;
      } catch {
        return fallbackUrl;
      }
    }

    function describe(el: Element): string {
      const id = el.id ? `#${el.id}` : '';
      const cls = typeof el.className === 'string' && el.className.trim()
        ? '.' + el.className.trim().split(/\s+/).slice(0, 2).join('.')
        : '';
      return `${el.tagName.toLowerCase()}${id}${cls}`;
    }

    function resolve(raw: string): string | null {
      const value = raw.trim();
      if (!value) return null;
      if (value.startsWith('blob:')) return value; // opaque but was generated by the page itself
      try {
        const url = new URL(value, document.baseURI);
        if (url.protocol !== 'http:' && url.protocol !== 'https:' && url.protocol !== 'data:') return null;
        return url.href;
      } catch {
        return null;
      }
    }

    function dedupeKey(source: string, el: Element, raw: string): string {
      return `${source}\u0000${describe(el)}\u0000${raw}`;
    }

    function waitForImage(resolvedUrl: string, existing?: HTMLImageElement): Promise<boolean> {
      return new Promise((done) => {
        const img = existing ?? new Image();
        let settled = false;
        const finish = (ok: boolean) => {
          if (settled) return;
          settled = true;
          done(ok);
        };

        if (img.complete && img.src) {
          finish(img.naturalWidth > 0);
          return;
        }

        const timer = setTimeout(() => finish(false), timeoutMs);
        img.addEventListener('load', () => { clearTimeout(timer); finish(img.naturalWidth > 0); }, { once: true });
        img.addEventListener('error', () => { clearTimeout(timer); finish(false); }, { once: true });
        if (!existing) img.src = resolvedUrl;
      });
    }

    function waitForVideo(video: HTMLVideoElement): Promise<boolean> {
      return new Promise((done) => {
        let settled = false;
        const finish = (ok: boolean) => {
          if (settled) return;
          settled = true;
          done(ok);
        };

        if (video.readyState >= 1 /* HAVE_METADATA */) {
          finish(true);
          return;
        }
        if (video.error) {
          finish(false);
          return;
        }

        const timer = setTimeout(() => finish(video.readyState >= 1), timeoutMs);
        video.addEventListener('loadedmetadata', () => { clearTimeout(timer); finish(true); }, { once: true });
        video.addEventListener('error', () => { clearTimeout(timer); finish(false); }, { once: true });
      });
    }

    function waitForIframe(frame: HTMLIFrameElement): Promise<boolean> {
      return new Promise((done) => {
        let settled = false;
        const finish = (ok: boolean) => {
          if (settled) return;
          settled = true;
          done(ok);
        };
        const timer = setTimeout(() => finish(true), Math.min(timeoutMs, 5_000));
        frame.addEventListener('load', () => { clearTimeout(timer); finish(true); }, { once: true });
        frame.addEventListener('error', () => { clearTimeout(timer); finish(false); }, { once: true });
      });
    }

    const checks: Promise<void>[] = [];

    function queueImageLike(raw: string | null, source: string, el: Element, existing?: HTMLImageElement) {
      if (raw === null) return;
      const key = dedupeKey(source, el, raw);
      if (seen.has(key)) return;
      seen.add(key);
      checked++;

      const resolved = resolve(raw);
      if (!resolved) {
        issues.push({ label: labelOf(el, raw), issueType: 'invalid-url', url: raw, source });
        return;
      }

      checks.push((async () => {
        const ok = await waitForImage(resolved, existing);
        if (!ok) issues.push({ label: labelOf(el, resolved), issueType: 'asset-not-loading', url: resolved, source });
      })());
    }

    function queueVideo(video: HTMLVideoElement, source: string, raw: string) {
      const key = dedupeKey(source, video, raw);
      if (seen.has(key)) return;
      seen.add(key);
      checked++;

      const resolved = resolve(raw);
      if (!resolved) {
        issues.push({ label: labelOf(video, raw), issueType: 'invalid-url', url: raw, source });
        return;
      }

      checks.push((async () => {
        const ok = await waitForVideo(video);
        if (!ok) issues.push({ label: labelOf(video, resolved), issueType: 'asset-not-loading', url: resolved, source });
      })());
    }

    function queueIframe(frame: HTMLIFrameElement, raw: string) {
      const key = dedupeKey('iframe[src]', frame, raw);
      if (seen.has(key)) return;
      seen.add(key);
      checked++;

      const resolved = resolve(raw);
      if (!resolved) {
        issues.push({ label: labelOf(frame, raw), issueType: 'invalid-url', url: raw, source: 'iframe[src]' });
        return;
      }

      checks.push((async () => {
        const ok = await waitForIframe(frame);
        if (!ok) issues.push({ label: labelOf(frame, resolved), issueType: 'asset-not-loading', url: resolved, source: 'iframe[src]' });
      })());
    }

    // img — the browser already resolves srcset for us via currentSrc/naturalWidth.
    for (const img of Array.from(document.querySelectorAll('img'))) {
      const raw = img.getAttribute('src') || img.getAttribute('data-src') || img.getAttribute('data-lazy-src') || img.getAttribute('data-original');
      if (raw) queueImageLike(raw, 'img[src]', img, img);
    }

    // picture > source: not independently renderable, so validate the URL and
    // probe loadability with a throwaway Image() rather than waiting on the img.
    for (const source of Array.from(document.querySelectorAll('picture source'))) {
      const srcset = source.getAttribute('srcset');
      const first = srcset ? srcset.trim().split(/\s*,\s*/)[0]?.split(/\s+/)[0] : null;
      const raw = first || source.getAttribute('src');
      if (raw) queueImageLike(raw, 'source[srcset]', source);
    }

    // video
    for (const video of Array.from(document.querySelectorAll('video'))) {
      const raw = video.getAttribute('src') || video.getAttribute('data-src') || video.getAttribute('data-video-src');
      if (raw) queueVideo(video, 'video[src]', raw);

      const poster = video.getAttribute('poster');
      if (poster) queueImageLike(poster, 'video[poster]', video);

      for (const s of Array.from(video.querySelectorAll('source'))) {
        const sSrc = s.getAttribute('src');
        if (sSrc) queueVideo(video, 'video source[src]', sSrc);
      }
    }

    // Video embeds (YouTube/Vimeo/DAM players).
    for (const frame of Array.from(document.querySelectorAll('iframe[src]'))) {
      const src = frame.getAttribute('src')!;
      if (/video|player|youtube|vimeo|scene7|brightcove/i.test(src)) {
        queueIframe(frame as HTMLIFrameElement, src);
      }
    }

    // CSS background images — hero banners are often set this way.
    for (const el of Array.from(document.querySelectorAll<HTMLElement>('*'))) {
      const bg = getComputedStyle(el).backgroundImage;
      if (!bg || bg === 'none') continue;
      for (const match of bg.matchAll(/url\((['"]?)(.*?)\1\)/g)) {
        queueImageLike(match[2], 'css[background-image]', el);
      }
    }

    await Promise.all(checks);

    return { assetsChecked: checked, issues };
  }, LOAD_TIMEOUT_MS);
}
